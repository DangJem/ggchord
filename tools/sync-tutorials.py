#!/usr/bin/env python3
"""Generate paired vignette source files without knitting or rendering."""
import argparse
import re
from documentation_lib import ROOT, WEB, PAGES, expand, localize_r_comments

INTRO_CHAPTERS = ('installation', 'multi-sequence-start', 'circular-start', 'dotplot-start', 'fusion-start')
CHAPTERS = [next(p for p in PAGES if p['slug'] == slug) for slug in INTRO_CHAPTERS]

def tutorial(lang):
    title = 'ggchord: sequence plots and composition' if lang == 'en' else 'ggchord：序列图与多视图组合说明'
    intro = ('Choose among four plotting modules. Each opening example includes its own setup. '
        'Continue online for data import, advanced workflows and complete research examples.' if lang == 'en' else
        '按任务选择四个绘图模块，每个模块都提供独立的首图代码。'
        '自备数据、专业专题和完整科研案例请继续查阅在线说明。')
    text = f'''---
title: "{title}"
output:
  rmarkdown::html_vignette:
    self_contained: true
    css: vignette.css
vignette: >
  %\\VignetteIndexEntry{{{title}}}
  %\\VignetteEngine{{knitr::rmarkdown}}
  %\\VignetteEncoding{{UTF-8}}
---

<!-- Generated by tools/sync-tutorials.py; edit website/ and tools/documentation-examples.R. -->

```{{r setup, include=FALSE}}
knitr::opts_chunk$set(eval = FALSE, collapse = TRUE, comment = "#>")
```

<img src="tutorial-assets/logo.png" alt="ggchord" width="200">

{intro}

'''

    for p in CHAPTERS:
        body = expand((WEB/lang/(p['slug']+'.md')).read_text(), lang, figures='tutorial-assets')
        body = re.sub(r'(?<=tutorial-assets/)([a-z]+)\.png', r'\1.jpg', body)
        # The website opens a separate full-size file. CRAN serves the vignette
        # HTML on its own, so retain only the image that Pandoc can embed.
        body = re.sub(r'<a class="figure-link"[^>]*>(<img [^>]*>)</a>', r'\1', body)
        body = re.sub(r' · <span class="figure-hint">[^<]*</span>', '', body)
        body = re.sub(r'^(#{2,5}) (.*?)(?: \{#([^}]+)\})?$',
            lambda m: '#'+m[1]+' '+m[2]+(f' {{#{p["slug"]}-{m[3]}}}' if m[3] else ''), body, flags=re.M)
        def lesson_link(match):
            label, slug, anchor = match.groups()
            if slug in INTRO_CHAPTERS:
                return f'[{label}](#{slug}' + (f'-{anchor}' if anchor else '') + ')'
            target = f'https://dangjem.github.io/ggchord/{lang}/{slug}.html'
            return f'[{label}]({target}' + (f'#{anchor}' if anchor else '') + ')'
        body = re.sub(r'\[([^\]]+)\]\(([a-z-]+)\.html(?:#([^)]*))?\)', lesson_link, body)
        body = body.replace('(../assets/source/', f'(https://dangjem.github.io/ggchord/assets/source/')
        body = re.sub(r'\(\.\./assets/(course\w+\.png)\)',r'(../man/figures/\1)',body)
        body = body.replace('(../build-manifest.json)', '(https://dangjem.github.io/ggchord/build-manifest.json)')
        body = body.replace('(../assets/tutorial-inputs.zip)', '(https://dangjem.github.io/ggchord/assets/tutorial-inputs.zip)')
        body = body.replace('(../assets/MIGRATION.md)', '(../MIGRATION.md)').replace('(../assets/MIGRATION-Hans.md)', '(../MIGRATION-Hans.md)')
        text += f'\n## {p["title"][lang]} {{#{p["slug"]}}}\n\n'+body+'\n'

    from documentation_lib import snippets
    heading = 'HSP点阵图与径向辐条' if lang == 'zh' else 'HSP Dotplot and radial spokes'
    summary = ('复用已有来源表，无需另一套比对表。Dotplot线段保留四个HSP端点，Radial使用已有环形邻接关系和真实长度比例。来源准备、支持图层与位置反查见网站view-expansion章节。' if lang == 'zh' else
        'Use the existing source tables; no extra alignment table is required. Dotplot segments retain all four HSP endpoints. Radial spokes use cyclic existing relationships and proportional lengths. See the website view-expansion chapter for source preparation, supported layers and inverse mapping.')
    text += '\n## ' + heading + ' {#view-expansion}\n\n' + summary + '\n\n```r\n' + snippets()['expansionminimal'] + '\n```\n'

    # R chunks share byte-identical code in both languages; never knit here.
    count = 0
    def chunk(m):
        nonlocal count
        count += 1
        return f'```{{r example-{count}, eval=FALSE}}\n{m[1]}\n```'
    text = re.sub(r'```r\n(.*?)\n```', chunk, text, flags=re.S)
    return text.rstrip()+"\n"

def readme(lang):
    """One README layout/code source with saved, reviewed prose translations."""
    import json
    template = (WEB/'readme-template.md').read_text()
    translations = json.loads((WEB/'readme-text.json').read_text())
    def replace(match):
        key = match[1]
        return lang if key == 'lang' else translations[key][lang]
    return re.sub(r'\{\{([a-z-]+)\}\}', replace, template)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for lang, name in [('en', 'ggchord_vignette.Rmd'), ('zh', 'ggchord_guide_hans.Rmd')]:
        path = ROOT/'vignettes'/name
        content = tutorial(lang)
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Out-of-date tutorial: {path}')
        else:
            path.write_text(content)
    for lang, name in [('en', 'README.md'), ('zh', 'README-Hans.md')]:
        path = ROOT/name
        content = readme(lang)
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Out-of-date README: {path}')
        else:
            path.write_text(content)
    print('Paired tutorials and README sources are synchronized; no vignette rendering performed.')

if __name__ == '__main__':
    main()
